#!/usr/bin/env python3
"""Build shell/core/emoji.js from Unicode's emoji-test.txt (fully-qualified, no skin tones), with
each emoji's short names (the :sob: kind) and tags from GitHub's gemoji db/emoji.json (MIT).
Usage: make_emoji.py emoji-test.txt [gemoji-emoji.json] > shell/core/emoji.js"""
import json, re, sys

# short names and tags by emoji (matched without the FE0F variation selector)
codes = {}
if len(sys.argv) > 2:
    for e in json.load(open(sys.argv[2], encoding="utf-8")):
        codes[e["emoji"].replace("\ufe0f", "")] = (e.get("aliases", []), e.get("tags", []))

groups, out, group = [], [], None
for line in open(sys.argv[1], encoding="utf-8"):
    if line.startswith("# group:"):
        group = line.split(":", 1)[1].strip()
        if group != "Component":
            groups.append(group)
        continue
    m = re.match(r"^([0-9A-F ]+)\s*;\s*fully-qualified\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$", line)
    if not m or group == "Component":
        continue
    cps = m.group(1).split()
    if any(c in ("1F3FB", "1F3FC", "1F3FD", "1F3FE", "1F3FF") for c in cps):
        continue  # skin-tone variants
    aliases, tags = codes.get(m.group(2).replace("\ufe0f", ""), ([], []))
    out.append([m.group(2), m.group(3).strip(), groups.index(group), " ".join(aliases), " ".join(tags)])

print(".pragma library")
print("// Generated by tools/make_emoji.py from Unicode's emoji-test.txt, short names and tags from")
print("// GitHub's gemoji (MIT): [emoji, name, group, short names, tags]")
print("var groups = " + json.dumps(groups) + ";")
print("var list = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";")
