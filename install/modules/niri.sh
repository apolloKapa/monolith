#!/usr/bin/env bash
# niri setup: modular config from monolith/compositors/niri, plus output.kdl and
# workspaces.kdl generated from the monitors on this machine.

NIRI_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/niri"

backup_niri_config() {
    [ -d "$NIRI_DIR" ] && [ -n "$(ls -A "$NIRI_DIR" 2>/dev/null)" ] || return 0
    local dest="${NIRI_DIR}_backup/backup_$(date +%Y%m%d_%H%M%S)"
    mkdir -p "$dest"
    cp -a "$NIRI_DIR/." "$dest/"
    echo -e "  ${C_CYAN}niri:${RESET} old config backed up to $dest"
}

# outputs as JSON from the running niri, or nothing when niri isn't running (e.g. from a TTY)
niri_outputs_json() {
    command -v niri &>/dev/null || return 1
    niri msg -j outputs 2>/dev/null | jq -e 'type == "object" and length > 0' >/dev/null 2>&1 || return 1
    niri msg -j outputs 2>/dev/null
}

# writes output.kdl to stdout
generate_niri_outputs() {
    local json="$1"
    echo "// Displays. Generated by the Monolith installer from the monitors it found."
    echo "// Run \`niri msg outputs\` to see names and modes."
    if [ -z "$json" ]; then
        echo "// niri wasn't running during install, so nothing is pinned: niri picks each"
        echo "// monitor's preferred mode. Re-run \`monolith installer\` from niri to pin the layout."
        return
    fi
    echo "$json" | jq -r '
        def transform:
            if . == null or . == "Normal" then empty
            else ascii_downcase | sub("flipped(?<d>[0-9]+)"; "flipped-\(.d)") end;
        to_entries | sort_by(.key)[] | .key as $n | .value as $o |
        if $o.current_mode == null or $o.logical == null then
            "\noutput \"\($n)\" {\n    off\n}"
        else
            ($o.modes[$o.current_mode]) as $m |
            ($m.refresh_rate | tostring) as $hz |   # millihertz, e.g. 239970 -> 239.970
            ([
                "    mode \"\($m.width)x\($m.height)@\($hz[0:-3]).\($hz[-3:])\"",
                "    position x=\($o.logical.x) y=\($o.logical.y)",
                "    scale \($o.logical.scale)"
            ] + ([$o.logical.transform | transform] | map("    transform \"\(.)\""))
              + (if $o.vrr_enabled then ["    variable-refresh-rate"] else [] end)) as $lines |
            "\noutput \"\($n)\" {\n" + ($lines | join("\n")) + "\n}"
        end'
}

# writes workspaces.kdl to stdout: 1-10 on the main monitor, d2-1..10 on a second one.
# Both sets are pinned with open-on-output, so when a monitor is turned off and on again its
# workspaces move back (unpinned ones stayed on the other monitor: 21 workspaces on one screen).
generate_niri_workspaces() {
    local json="$1" main="" second=""
    if [ -n "$json" ]; then
        # main = the monitor at 0,0 (or the first one on); second = the next one that's on
        main=$(echo "$json" | jq -r '
            [to_entries[] | select(.value.logical != null)] as $on |
            ($on | map(select(.value.logical.x == 0 and .value.logical.y == 0)) | first // $on[0]) | .key // empty')
        second=$(echo "$json" | jq -r --arg main "$main" '
            [to_entries[] | select(.value.logical != null and .key != $main)] | sort_by(.key) | first | .key // empty')
    fi
    echo "// Workspaces 1-10 always exist (they don't vanish when empty)."
    if [ -n "$main" ]; then
        echo "// Pinned to $main so they move back to it when it's turned off and on again."
        for i in $(seq 1 10); do echo "workspace \"$i\" { open-on-output \"$main\"; }"; done
    else
        for i in $(seq 1 10); do echo "workspace \"$i\""; done
    fi
    [ -n "$second" ] || return
    echo ""
    echo "// Second monitor ($second) has its own set, named d2-1..d2-10."
    for i in $(seq 1 10); do echo "workspace \"d2-$i\" { open-on-output \"$second\"; }"; done
}

# spawn-at-startup lines in the current niri config that aren't in Monolith's default
# (and aren't the old shell), i.e. the user's own startup apps
personal_startup_lines() {
    local src="$1"
    [ -d "$NIRI_DIR" ] || return 0
    local defaults
    defaults="$(grep -rhE '^\s*spawn(-sh)?-at-startup' "$src" 2>/dev/null | sed 's/^\s*//')"
    grep -rhE '^\s*spawn(-sh)?-at-startup' "$NIRI_DIR" --include='*.kdl' 2>/dev/null | sed 's/^\s*//' \
        | grep -v -e serpantinum -e monolithd \
        | grep -vxF -f <(printf '%s\n' "$defaults") \
        | awk '!seen[$0]++'
}

# the bare `spawn-at-startup "monolithd" "start"` needs ~/.local/bin on niri's PATH, which a
# fresh PC doesn't have: switch it to the full-path line from autostart.kdl, wherever it is
upgrade_monolithd_autostart() {
    local f
    for f in "$NIRI_DIR"/config.kdl "$NIRI_DIR"/config/*.kdl; do
        [ -f "$f" ] || continue
        grep -qE '^[[:space:]]*spawn-at-startup "monolithd" "start"' "$f" || continue
        sed -i 's|^\([[:space:]]*\)spawn-at-startup "monolithd" "start".*$|\1spawn-at-startup "bash" "-c" "export PATH=\\"$HOME/.local/bin:$PATH\\"; exec \\"$HOME/.local/bin/monolithd\\" start"|' "$f"
    done
}

# switches the old screenshot binds (niri's built-in screenshots, grim + swappy) to Monolith's
# screenshot tool, wherever they appear; leaves any other bind alone
upgrade_screenshot_binds() {
    local f="$1"
    [ -f "$f" ] || return 0
    python3 - "$f" <<'PY'
import re, sys
path = sys.argv[1]
text = open(path).read()
new = {
    "Print": 'spawn "monolith" "screenshot";',
    "Ctrl+Print": 'spawn "monolith" "screenshot" "--full";',
    "Alt+Print": 'spawn "monolith" "screenshot" "--full" "--edit";',
    "Mod+Shift+S": 'spawn "monolith" "screenshot";',
}
old = {
    "Print": r'screenshot;',
    "Ctrl+Print": r'screenshot-screen;',
    "Alt+Print": r'screenshot-window;',
    "Mod+Shift+S": r'spawn-sh "grim -g \\"\$\(slurp\)\\" - \| swappy -f -";',
}
changed = 0
for key, body in old.items():
    pat = re.compile(r'^([ \t]*)' + re.escape(key) + r'(\s[^{\n]*)?\{\s*' + body + r'\s*\}[ \t]*$', re.M)
    text, n = pat.subn(lambda m: f'{m.group(1)}{key}{m.group(2) or " "}{{ {new[key]} }}', text)
    changed += n
# extra combos, added next to Print if they aren't bound yet
extra = [("Shift+Print", 'spawn "monolith" "screenshot" "--edit";'), ("Mod+Print", 'spawn "monolith" "screenshot" "--full";')]
m = re.search(r'^([ \t]*)Print\s*\{[^\n]*\}[ \t]*$', text, re.M)
if m:
    add = "".join(f"\n{m.group(1)}{k} {{ {b} }}" for k, b in extra if not re.search(r'^\s*' + re.escape(k) + r'[\s{]', text, re.M))
    if add:
        text = text[:m.end()] + add + text[m.end():]
        changed += add.count("\n")
open(path, "w").write(text)
print(changed)
PY
}

setup_niri_config() {
    local project_root="$1"
    local mode="${2:-replace}"   # replace | keep
    local src="$project_root/monolith/compositors/niri"

    if [ "$mode" = "keep" ] && [ -f "$NIRI_DIR/config.kdl" ]; then
        echo -e "  ${C_CYAN}niri:${RESET} keeping your existing config"
        grep -q "monolithd" -r "$NIRI_DIR" 2>/dev/null || \
            echo -e "  ${C_YELLOW}niri:${RESET} add  spawn-at-startup \"monolithd\" \"start\"  to it so the shell starts"
        return 0
    fi

    # the default config only starts what Monolith needs; keep the user's own startup apps
    local own_startup
    own_startup="$(personal_startup_lines "$src")"

    backup_niri_config
    rm -rf "$NIRI_DIR"
    mkdir -p "$NIRI_DIR/config"
    cp -r "$src/." "$NIRI_DIR/"
    if [ -n "$own_startup" ]; then
        printf '\n// your startup apps, kept from your previous niri config\n%s\n' "$own_startup" >> "$NIRI_DIR/config/autostart.kdl"
        echo -e "  ${C_CYAN}niri:${RESET} kept your startup apps: $(echo "$own_startup" | wc -l)"
    fi

    set_niri_keyboard_layout "$NIRI_DIR/config/input.kdl"

    local json=""
    json="$(niri_outputs_json)" || json=""
    generate_niri_outputs "$json" > "$NIRI_DIR/config/output.kdl"
    generate_niri_workspaces "$json" > "$NIRI_DIR/config/workspaces.kdl"

    if command -v niri &>/dev/null && ! niri validate -c "$NIRI_DIR/config.kdl" >/dev/null 2>&1; then
        # older niri versions can't `include`: merge everything into one config.kdl
        flatten_niri_config
        if ! niri validate -c "$NIRI_DIR/config.kdl" >/dev/null 2>&1; then
            echo -e "  ${C_RED}niri:${RESET} the generated config doesn't validate, run: niri validate"
            return 0
        fi
        echo -e "  ${C_YELLOW}niri:${RESET} this niri can't split its config into files, so it's all in config.kdl"
    fi
    echo -e "  ${C_GREEN}niri:${RESET} config written to $NIRI_DIR"
}

# this PC's keyboard layout (what localectl / vconsole.conf say), not the one the config shipped with
set_niri_keyboard_layout() {
    local file="$1" layout="" variant=""
    [ -f "$file" ] || return 0
    if command -v localectl &>/dev/null; then
        layout="$(localectl status 2>/dev/null | awk -F': *' '/X11 Layout/{print $2; exit}')"
        variant="$(localectl status 2>/dev/null | awk -F': *' '/X11 Variant/{print $2; exit}')"
    fi
    [ -z "$layout" ] && layout="$(sed -n 's/^XKBLAYOUT=//p' /etc/vconsole.conf 2>/dev/null | tr -d '"' | head -1)"
    [ -z "$variant" ] && variant="$(sed -n 's/^XKBVARIANT=//p' /etc/vconsole.conf 2>/dev/null | tr -d '"' | head -1)"
    layout="$(printf '%s' "${layout:-us}" | tr -cd 'a-zA-Z0-9,_()-')"
    variant="$(printf '%s' "$variant" | tr -cd 'a-zA-Z0-9,_()-')"
    [ -n "$layout" ] || layout="us"
    sed -i "s|^\([[:space:]]*\)layout \"[^\"]*\"|\1layout \"$layout\"|" "$file"
    if [ -n "$variant" ] && ! grep -q '^[[:space:]]*variant ' "$file"; then
        sed -i "s|^\([[:space:]]*\)layout \"$layout\"|&\n\1variant \"$variant\"|" "$file"
    fi
    echo -e "  ${C_CYAN}niri:${RESET} keyboard layout $layout${variant:+ ($variant)}"
}

# replaces each `include "x"` line in config.kdl with the contents of x
flatten_niri_config() {
    local out="$NIRI_DIR/config.kdl.flat" line inc
    : > "$out"
    while IFS= read -r line; do
        if [[ "$line" =~ ^[[:space:]]*include[[:space:]]+\"([^\"]+)\" ]]; then
            inc="${BASH_REMATCH[1]}"
            printf '\n// ---- %s ----\n' "$inc" >> "$out"
            cat "$NIRI_DIR/$inc" >> "$out" 2>/dev/null
        else
            printf '%s\n' "$line" >> "$out"
        fi
    done < "$NIRI_DIR/config.kdl"
    mv "$out" "$NIRI_DIR/config.kdl"
}
